"""Regenerate the combat icons and bring the wiki up to date with them.

    python deploy.py                         regenerate, then list what differs from the wiki
    python deploy.py -wiki LOGIN PASSWORD    ...and upload and publish it

Runs generate_atlas.py, then updates whatever differs from the wiki's copy, in this order:
  File:Combat_Icon_Atlas.webp       the atlas in output/, compared by SHA-1
  Template:CombatIcon/styles.css    output/combat-icons.css
  Template:CombatIcon               wiki/CombatIcon.wikitext
  Template:CombatIcon/list          output/icon-list.wikitext
The stylesheet names the atlas's version in its URL, so the atlas goes first and nothing fetches
that version before it is there. The stylesheet has to exist before the template is used.

Nothing is changed if the new stylesheet would give a cell of the wiki's atlas file to another
icon (a re-packed layout, or an output/icons.json other than the one last deployed): pages still
cached with the old stylesheet would show the wrong glyphs. Upload a re-packed atlas under a new
name (--wiki-file), or pass --allow-moves to publish anyway.
"""
import argparse
import difflib
import hashlib
import io
import json
import os
import re
import sys

import requests

import generate_atlas
from iconpack.layout import LAYOUT_FILE
from iconpack.wiki import ApiError, Site

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'output')
TEMPLATE = 'Template:CombatIcon'
STYLES = TEMPLATE + '/styles.css'
LIST = TEMPLATE + '/list'
SOURCES = {  # in the order they are published
    STYLES: os.path.join(OUT, 'combat-icons.css'),
    TEMPLATE: os.path.join(HERE, 'wiki', 'CombatIcon.wikitext'),
    LIST: os.path.join(OUT, 'icon-list.wikitext'),
}
# wikitext of the atlas's file page, if the upload creates it
FILE_PAGE = ('Glyph atlas of [[Template:CombatIcon]]: the symbols of the combat status icons, which the '
             "template's stylesheet draws inside their frames. Generated by ba-iconpack; every icon keeps "
             'its place in it from one version to the next.')

CELL = re.compile(r'\[data-icon="([^"]+)"\]\s*\{\s*--ci-col:\s*(\d+);\s*--ci-row:\s*(\d+);\s*\}')
ATLAS_URL = re.compile(r'url\("([^"?]+)')
ATLAS_SIZE = re.compile(r'background-size:[^;]*')


def read_text(path):
    """The file's text as the wiki keeps it: LF line ends, no trailing whitespace."""
    with open(path, encoding='utf-8') as fh:
        return fh.read().replace('\r\n', '\n').rstrip()


def cells(css):
    """The icon in each cell of the atlas, (column, row) -> id, as the stylesheet places them."""
    return {(int(m[2]), int(m[3])): m[1] for m in CELL.finditer(css)}


def first(pattern, text):
    """The pattern's first match in the text (its group, if it has one), or None."""
    m = pattern.search(text)
    if m is None:
        return None
    return m[1] if pattern.groups else m[0]


def mix_ups(old_css, new_css):
    """Where a page cached with one stylesheet would get the other's atlas, both using the same
    file: icons that would show another icon's glyph, as 'old -> new' cell owners."""
    if first(ATLAS_SIZE, old_css) != first(ATLAS_SIZE, new_css):
        return ['every icon: the atlas changed width']
    old, new = cells(old_css), cells(new_css)
    return [f'{old[c]} -> {new[c]}' for c in sorted(old.keys() & new.keys()) if old[c] != new[c]]


def icon_changes(old_ids, new_ids):
    """What an edit summary says about the icons, after the atlas version."""
    if old_ids is None:
        return f': {len(new_ids)} icons'
    added, dropped = sorted(new_ids - old_ids), sorted(old_ids - new_ids)
    parts = ([f'added {generate_atlas.names(added, 8)}'] if added else []) + \
            ([f'dropped {generate_atlas.names(dropped, 8)}'] if dropped else [])
    return ': ' + '; '.join(parts) if parts else ''


def deploy(args):
    with open(os.path.join(OUT, LAYOUT_FILE), encoding='utf-8') as fh:
        atlas = json.load(fh)['atlas']
    with open(os.path.join(OUT, atlas['file']), 'rb') as fh:
        data = fh.read()
    sha1 = hashlib.sha1(data).hexdigest()
    texts = {title: read_text(path) for title, path in SOURCES.items()}
    file_title = f"File:{atlas['file']}"

    site = Site()
    if args.wiki:
        try:
            site.login(*args.wiki)
        except ApiError as error:
            sys.exit(f"Login failed: {error.data.get('reason', error.data) if isinstance(error.data, dict) else error}")
        print(f'Logged in to the wiki as {args.wiki[0]}')
    published = site.texts(list(SOURCES))
    remote = site.file(atlas['file'])

    # cached pages mix stylesheets and atlases for a while, so no cell may change hands
    new_css, old_css = texts[STYLES], published[STYLES]
    new_url = first(ATLAS_URL, new_css)
    problems = []
    if old_css is not None and first(ATLAS_URL, old_css) == new_url:
        mixed = mix_ups(old_css, new_css)
        if mixed:
            problems = [f"The new atlas puts other icons in cells of {file_title} that the wiki's stylesheet "
                        'uses. Until caches catch up, a page with one stylesheet and the other atlas would show '
                        'the icon before the arrow with the glyph after it, or the other way round:',
                        generate_atlas.names(mixed, 12)]
    elif old_css is not None and remote is not None and remote['sha1'] != sha1:
        problems = [f"{file_title} is on the wiki with other contents, but the wiki's stylesheet uses another "
                    'file. Pages cached from when a stylesheet used it may still do, and would show the wrong '
                    'glyphs once it is replaced.']
    if problems:
        print('\n  '.join(problems))
        if not args.allow_moves:
            sys.exit('Nothing was changed. Restore the output/icons.json last deployed, upload a re-packed '
                     'atlas under a new name (--wiki-file), or pass --allow-moves.')
        print('Going ahead (--allow-moves)')

    old_ids = set(cells(old_css).values()) if old_css is not None else None
    changes = icon_changes(old_ids, set(cells(new_css).values()))
    summaries = {
        STYLES: f"Stylesheet of atlas {atlas['version']}{changes}",
        TEMPLATE: 'Template from ba-iconpack (wiki/CombatIcon.wikitext)',
        LIST: f"Icons of atlas {atlas['version']}{changes}",
    }

    def check_url(then):
        """The stylesheet has to find the atlas where the wiki serves it."""
        if remote is not None and remote['url'] != new_url:
            sys.exit(f"The wiki serves {file_title} from {remote['url']}, but the stylesheet looks for it at "
                     f'{new_url}. {then}')

    check_url('Nothing was changed.')
    if remote is not None and remote['sha1'] == sha1:
        print(f'{file_title}: no changes')
    elif not args.wiki:
        print(f"{file_title}: would upload {'it' if remote is None else 'a new version'}")
    else:
        site.upload(data, atlas['file'], f"Atlas {atlas['version']}{changes}", FILE_PAGE)
        remote = site.file(atlas['file'])
        if remote is None or remote['sha1'] != sha1:
            sys.exit(f"{file_title}: the wiki doesn't have the uploaded version; stopping before the stylesheet")
        print(f'{file_title}: uploaded')
        check_url('Stopping before the stylesheet.')

    edited = []
    for title, new in texts.items():
        old = published[title]
        if old == new:
            print(f'{title}: no changes')
            continue
        diff = list(difflib.unified_diff((old or '').splitlines(), new.splitlines(), 'wiki', 'local', lineterm='', n=1))
        added = sum(line[:1] == '+' and not line.startswith('+++') for line in diff)
        removed = sum(line[:1] == '-' and not line.startswith('---') for line in diff)
        what = 'create' if old is None else f'update (+{added} -{removed} lines)'
        if args.diff:
            print('\n'.join(diff))
        if not args.wiki:
            print(f'{title}: would {what}')
            continue
        site.edit(title, new, summaries[title])
        edited.append(title)
        print(f"{title}: {'created' if old is None else what.replace('update', 'updated')}")

    # the wiki keeps pages as they are sent but for line ends and trailing whitespace, which read_text
    # matches; a page it changed otherwise would be published again by every run
    if edited:
        for title, text in site.texts(edited).items():
            if text != texts[title]:
                print(f'Warning: the wiki saved {title} differently from {SOURCES[title]}')
    if not args.wiki:
        print('Nothing was changed on the wiki; pass -wiki LOGIN PASSWORD to upload and publish.')


def main():
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(errors='backslashreplace')  # diffs may hold what the console can't show
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-wiki', '--wiki', nargs=2, metavar=('LOGIN', 'PASSWORD'),
                    help='log in to upload and publish (a bot password); without it, only list what would be')
    ap.add_argument('--icons', help='source icon directory (generate_atlas.py --icons)')
    ap.add_argument('--wiki-file', help='file name of the atlas on the wiki (generate_atlas.py --wiki-file)')
    ap.add_argument('--no-generate', action='store_true', help='publish output/ as it is, without regenerating it')
    ap.add_argument('--allow-moves', action='store_true',
                    help="publish even if icons would change cells of the wiki's atlas file")
    ap.add_argument('--diff', action='store_true', help="show how each page differs from the wiki's")
    args = ap.parse_args()

    if args.no_generate:
        if args.icons or args.wiki_file:
            ap.error('--icons and --wiki-file are for regenerating, which --no-generate skips')
    else:
        generate_atlas.main(['--out', OUT] + (['--icons', args.icons] if args.icons else [])
                            + (['--wiki-file', args.wiki_file] if args.wiki_file else []))
        print()
    try:
        deploy(args)
    except (ApiError, requests.HTTPError) as error:
        details = error.data if isinstance(error, ApiError) and isinstance(error.data, dict) else ''
        sys.exit(f'Wiki error, stopping: {error} {details}'.rstrip())
    return 0


if __name__ == '__main__':
    sys.exit(main())
