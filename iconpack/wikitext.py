"""Wikitext of Template:CombatIcon/list, the list of icons on the template's page.

The list is a page of its own, which the template's documentation transcludes, so updating it
after a game update doesn't touch the template and re-render every page that uses it.
"""

TEMPLATE = 'CombatIcon'
HEADER = '<!-- Generated by ba-iconpack (generate_atlas.py); edit the generator rather than this page. -->\n'
GRID = ('display:grid; grid-template-columns:repeat(auto-fill, minmax(20em, 1fr)); gap:4px 16px; '
        'overflow-wrap:anywhere; --combat-icon-size:32px')


def build_icon_list(records, types):
    """records: icons.json records; types: icon types in the order to list them."""
    groups = {}
    for r in records:
        groups.setdefault(r['type'], []).append(r)
    order = {t: i for i, t in enumerate(types)}
    out = [HEADER]
    for icon_type in sorted(groups, key=lambda t: (order.get(t, len(order)), t)):
        # one block-level line per icon, so the parser doesn't wrap them in a paragraph
        out.append(f'=== {icon_type} ===\n<div style="{GRID}">\n')
        for r in sorted(groups[icon_type], key=lambda r: r['id'].casefold()):
            text = f"<code>{r['id']}</code>"
            if r.get('missing'):
                text += " (no longer in the game's files)"
            out.append('<div>{{' + TEMPLATE + '|' + r['id'] + '|text=' + text + '}}</div>\n')
        out.append('</div>\n')
    return ''.join(out)
